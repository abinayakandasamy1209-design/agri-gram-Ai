#  3. ANALYTICS SUMMARY (extra stats for dashboard)
# ============================================================
def analytics_summary():
    """Return summary stats + water comparison for the dashboard."""
    from agri_features import CROP_ECONOMICS

    water_map = {
        "Rice": 1200, "Wheat": 450, "Cotton": 700, "Sugarcane": 1800,
        "Groundnut": 500, "Maize": 600, "Millets": 350, "Pulses": 400,
        "Vegetables": 550, "Coconut": 900,
    }
    crops = list(CROP_ECONOMICS.keys())

    profit_list, water_list = [], []
    for c in crops:
        info = CROP_ECONOMICS[c]
        profit = info["yield"] * info["price"] - info["cost"]
        profit_list.append({"crop": c, "profit": round(profit)})
        water_list.append({"crop": c, "water_mm": water_map.get(c, 500)})

    profit_list.sort(key=lambda x: x["profit"], reverse=True)
    water_list.sort(key=lambda x: x["water_mm"])

    best = profit_list[0]
    least_water = water_list[0]
    return {
        "total_crops": len(crops),
        "most_profitable": best["crop"],
        "most_profitable_value": best["profit"],
        "least_water_crop": least_water["crop"],
        "least_water_value": least_water["water_mm"],
        "profit_comparison": profit_list,
        "water_comparison": water_list,
    }
