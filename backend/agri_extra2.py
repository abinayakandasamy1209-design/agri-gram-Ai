def send_sms(to_number, message):
    """
    Send an SMS via Twilio.
    Set these environment variables (or replace below):
      TWILIO_SID, TWILIO_TOKEN, TWILIO_FROM
    Requires: twilio
    Returns a status dict (does not crash if not configured).
    """
    sid = os.environ.get("TWILIO_SID", "")
    token = os.environ.get("TWILIO_TOKEN", "")
    from_num = os.environ.get("TWILIO_FROM", "")

    if not (sid and token and from_num):
        return {
            "sent": False,
            "reason": "Twilio not configured. Set TWILIO_SID, TWILIO_TOKEN, "
                      "TWILIO_FROM environment variables.",
            "demo_message": message,
            "to": to_number
        }

    try:
        from twilio.rest import Client
        client = Client(sid, token)
        msg = client.messages.create(body=message, from_=from_num, to=to_number)
        return {"sent": True, "sid": msg.sid, "to": to_number}
    except Exception as e:
        return {"sent": False, "reason": str(e), "to": to_number}


