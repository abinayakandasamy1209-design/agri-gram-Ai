# ============================================================
#  FAST2SMS (India) - send real SMS easily
# ============================================================
def send_sms_fast2sms(to_number, message):
    """
    Send an SMS via Fast2SMS (India).
    Set environment variable FAST2SMS_KEY with your API key.
    Get a free key at https://www.fast2sms.com (Dev API -> API Key).
    `to_number` should be a 10-digit Indian number (no +91).
    Requires: requests
    """
    api_key = os.environ.get("FAST2SMS_KEY", "")
    # Keep only the last 10 digits (Fast2SMS wants plain 10-digit numbers)
    digits = "".join(ch for ch in to_number if ch.isdigit())[-10:]

    if not api_key:
        return {
            "sent": False,
            "reason": "Fast2SMS not configured. Set FAST2SMS_KEY environment "
                      "variable (get a free key at fast2sms.com).",
            "demo_message": message,
            "to": digits,
        }

    try:
        import requests
        url = "https://www.fast2sms.com/dev/bulkV2"
        payload = {
            "route": "q",              # quick transactional route
            "message": message,
            "language": "english",
            "numbers": digits,
        }
        headers = {"authorization": api_key}
        r = requests.post(url, data=payload, headers=headers, timeout=10)
        data = r.json()
        if data.get("return") is True:
            return {"sent": True, "provider": "Fast2SMS",
                    "request_id": data.get("request_id"), "to": digits}
        return {"sent": False, "reason": str(data), "to": digits}
    except Exception as e:
        return {"sent": False, "reason": str(e), "to": digits}


# ============================================================
#  1. PDF REPORT GENERATION
# ============================================================
def generate_pdf_report(data):
    """
    Build a farmer report PDF in memory and return the bytes.
    `data` is a dict with optional keys: farmer_name, location, crop,
    soil, water, weather_summary, profit, yield_kg, notes.
    Requires: reportlab
    """
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.units import mm
    from reportlab.lib import colors
    from reportlab.platypus import (SimpleDocTemplate, Paragraph, Spacer,
                                    Table, TableStyle)
    from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle

    buffer = io.BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=A4,
                            topMargin=20*mm, bottomMargin=20*mm)
    styles = getSampleStyleSheet()
    green = colors.HexColor("#2e7d32")

    title_style = ParagraphStyle("t", parent=styles["Title"],
                                 textColor=green, fontSize=22)
    h2 = ParagraphStyle("h2", parent=styles["Heading2"], textColor=green)
    normal = styles["Normal"]

    elems = []
    elems.append(Paragraph("🌾 Agri Gram AI - Farm Report", title_style))
    elems.append(Paragraph(
        f"Generated: {datetime.now().strftime('%d %B %Y, %I:%M %p')}", normal))
    elems.append(Spacer(1, 8*mm))

    # Farmer / field info
    info_rows = [
        ["Farmer Name", data.get("farmer_name", "-")],
        ["Location", data.get("location", "-")],
        ["Selected Crop", data.get("crop", "-")],
        ["Soil Type", data.get("soil", "-")],
    ]
    t = Table(info_rows, colWidths=[60*mm, 100*mm])
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#e8f5e9")),
        ("TEXTCOLOR", (0, 0), (0, -1), green),
        ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
        ("PADDING", (0, 0), (-1, -1), 6),
    ]))
    elems.append(t)
    elems.append(Spacer(1, 8*mm))

    # Recommendations section
    elems.append(Paragraph("Recommendations", h2))
    recs = [
        ["Water Requirement", data.get("water", "-")],
        ["Weather Summary", data.get("weather_summary", "-")],
        ["Expected Yield", data.get("yield_kg", "-")],
        ["Estimated Profit", data.get("profit", "-")],
    ]
    t2 = Table(recs, colWidths=[60*mm, 100*mm])
    t2.setStyle(TableStyle([
        ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
        ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
        ("PADDING", (0, 0), (-1, -1), 6),
    ]))
    elems.append(t2)
    elems.append(Spacer(1, 8*mm))

    if data.get("notes"):
        elems.append(Paragraph("Notes", h2))
        elems.append(Paragraph(data["notes"], normal))

    elems.append(Spacer(1, 12*mm))
    elems.append(Paragraph(
        "<i>Report generated by Agri Gram AI - Smart Farming Assistant "
        "by Abinaya K</i>", normal))

    doc.build(elems)
    buffer.seek(0)
    return buffer


